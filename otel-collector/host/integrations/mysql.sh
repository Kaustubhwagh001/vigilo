#!/usr/bin/env bash
# ------------------------------------------------------------
# vigilo — OTel Collector (host, Contrib) — MySQL / MariaDB
# Purpose: render the native `mysql` receiver block (metrics, logs) for
#          the host-level otelcol-contrib collector (installed via the
#          .deb package by otel-collector/host/linux/*.sh) and print
#          wiring instructions — this script does NOT install the
#          collector binary itself.
# Requires env: MYSQL_HOST, MYSQL_USER, MYSQL_PASSWORD, TENANT_ID
# Optional env: DEPLOYMENT_ENVIRONMENT, OTELCOL_CONF_DIR
# Usage: sudo ./mysql.sh
#
# Uses the OTel Collector Contrib `mysqlreceiver`
# (https://github.com/open-telemetry/opentelemetry-collector-contrib/tree/main/receiver/mysqlreceiver)
# — a direct connection to mysqld/mariadbd, not a Prometheus scrape of a
# sidecar exporter. That's the genuinely different mechanism from
# grafana-agent/integrations/mysql.sh (which drives the classic Grafana
# Agent's built-in mysqld_exporter integration instead). MYSQL_HOST/USER/
# PASSWORD here are intentionally distinct env vars from that script's
# MYSQL_EXPORTER_HOST/USER/PASSWORD — there is no exporter process in this
# mechanism, just a direct DB connection, so reusing the "_EXPORTER_" name
# would be misleading.
#
# Dedup note: the source had two MySQL configs, differing mainly in how
# the target host was supplied and which tenant they ran under. One used
# a static IP and a tenant/resourcedetection set matching the other
# datastores' configs; the other used an Ansible Jinja expression for the
# endpoint ({{ ansible_host | default(inventory_hostname) }}), confirming
# these per-datastore configs were originally rendered per-host by Ansible
# across a fleet, and ran under a visibly different (real, redacted —
# see the sanitization report) tenant name, plus a narrower
# resourcedetection detector list and no journald receiver. Since this
# script parameterizes host/user/password/
# tenant via env vars regardless, both collapse into one canonical
# mysql.sh — the broader resourcedetection list and the journald receiver
# (both genuine capability, not cruft) are kept from the first; the
# `debug` exporter addition from the second is noted below as optional.
# ------------------------------------------------------------
set -euo pipefail

: "${MYSQL_HOST:?set MYSQL_HOST, e.g. 10.0.0.12:3306}"
: "${MYSQL_USER:?set MYSQL_USER, e.g. otel_metrics_reader}"
: "${MYSQL_PASSWORD:?set MYSQL_PASSWORD}"
: "${TENANT_ID:?set TENANT_ID, e.g. my-tenant}"

DEPLOYMENT_ENVIRONMENT="${DEPLOYMENT_ENVIRONMENT:-prod}"
OTELCOL_CONF_DIR="${OTELCOL_CONF_DIR:-/etc/otelcol-contrib/conf.d}"

sudo mkdir -p "${OTELCOL_CONF_DIR}"

sudo tee "${OTELCOL_CONF_DIR}/mysql.yaml" >/dev/null <<EOF
# Generated by otel-collector/host/integrations/mysql.sh — do not hand
# edit; re-run the script to regenerate. This is NOT a standalone
# collector config: it's a fragment to merge into (or include from) the
# host-level otelcol-contrib config installed by
# otel-collector/host/linux/*.sh. See that config's own receivers:/
# processors:/service.pipelines: sections and splice the blocks below in —
# otelcol-contrib does not reliably merge pipeline receiver lists across
# multiple --config files, so this is meant to be copy/merged by hand (or
# by your own config-management templating) rather than included
# automatically.

receivers:
  mysql:
    endpoint: ${MYSQL_HOST}
    username: ${MYSQL_USER}
    password: ${MYSQL_PASSWORD}
    collection_interval: 1m
    initial_delay: 10s
    statement_events:
      digest_text_limit: 120
      time_limit: 24h
      limit: 250

  filelog/mysql:
    include:
      - /var/log/mysql/*.log
    include_file_name: false
    include_file_path: true
    start_at: end

  journald/mysql:
    directory: /run/log/journal
    units:
      - ssh
      - mysqld
      - mysql
    priority: info

processors:
  resource/mysql:
    attributes:
      - key: service.name
        value: "mysql"
        action: upsert
      - key: tenant.id
        value: "${TENANT_ID}"
        action: upsert
      - key: deployment.environment
        value: "${DEPLOYMENT_ENVIRONMENT}"
        action: upsert

# Wiring instructions (manual merge into the host collector's config):
#   1. Add the three receivers above (mysql, filelog/mysql, journald/
#      mysql) to the top-level receivers: block.
#   2. Add resource/mysql to the top-level processors: block.
#   3. In service.pipelines:
#        metrics: add mysql to receivers, resource/mysql to processors.
#        logs: add filelog/mysql and journald/mysql to receivers,
#          resource/mysql to processors.
#      Optional: one source config also added a \`debug:\` exporter
#      (emits received telemetry to collector logs) for local
#      troubleshooting — add it to exporters: and the pipeline's
#      exporters list if you want that during initial rollout.
#   4. Restart otelcol-contrib: sudo systemctl restart otelcol-contrib
#
# ------------------------------------------------------------
# Granting the read-only metrics user its MySQL/MariaDB privileges (run
# once per DB host, as an admin, from a MySQL/MariaDB client):
#
#   SELECT User, Host FROM mysql.user;
#   GRANT PROCESS, REPLICATION CLIENT, SELECT ON *.* TO '\${MYSQL_USER}'@'<collector-host-or-%>';
#   FLUSH PRIVILEGES;
#
# (Source note: the GRANT's host clause was the literal IP of the
# collector host reaching in — scope it to the collector's actual
# address, or '%' if that's not practical in your network, rather than
# granting to every host.)
# ------------------------------------------------------------
EOF

echo "Wrote ${OTELCOL_CONF_DIR}/mysql.yaml"
echo "This fragment is NOT auto-loaded — merge it into the host otelcol-contrib config per the instructions in the file, then: sudo systemctl restart otelcol-contrib"
