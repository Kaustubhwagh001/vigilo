#!/usr/bin/env bash
# ------------------------------------------------------------
# vigilo — OTel Collector Contrib — ScyllaDB
# Purpose: render a `prometheus` receiver scrape job for an externally-run
#          scylla_exporter as a standalone config snippet, for merging into
#          the host-level otelcol-contrib config.
# Requires env: SCYLLA_EXPORTER_TARGET
# Optional env: SCYLLA_OTEL_SCRAPE_INTERVAL, OTELCOL_CONF_DIR
# Usage: sudo ./scylladb.sh
#
# Note: this migrates `scylla-otelcm.yml` from the source onboarding
# configs. ScyllaDB has no native OTel Collector receiver (same situation
# as grafana-agent/integrations/scylladb.sh), so this just scrapes
# scylla_exporter's /metrics via the prometheus receiver. The source file's
# `hostmetrics` block and its own `otel-collector-binary` self-scrape job
# (localhost:8888) are generic host-level collector config — not Scylla-
# specific — and are already the job of otel-collector/host/linux/'s base
# config, so they're dropped here rather than duplicated.
#
# This script does NOT install the otelcol-contrib binary or write the
# host's main config — that's owned by otel-collector/host/linux/'s
# installer. It only writes a receiver-only YAML snippet and prints the
# exact merge steps, since the collector does not deep-merge pipeline
# receiver lists across multiple --config files.
# ------------------------------------------------------------
set -euo pipefail

: "${SCYLLA_EXPORTER_TARGET:?set SCYLLA_EXPORTER_TARGET, e.g. 10.0.0.17:9180 (host:port of a running scylla_exporter / scylla-manager-agent)}"

SCYLLA_OTEL_SCRAPE_INTERVAL="${SCYLLA_OTEL_SCRAPE_INTERVAL:-60s}"
OTELCOL_CONF_DIR="${OTELCOL_CONF_DIR:-/etc/otelcol-contrib/conf.d}"

sudo mkdir -p "${OTELCOL_CONF_DIR}"

CONFIG="$(cat <<EOF
# Generated by otel-collector/host/integrations/scylladb.sh — merge into
# the host otelcol-contrib config; see the script header for exact steps.
receivers:
  prometheus/scylla:
    config:
      global:
        scrape_interval: ${SCYLLA_OTEL_SCRAPE_INTERVAL}
      scrape_configs:
        - job_name: 'scylla-exporter'
          metrics_path: /metrics
          scrape_interval: ${SCYLLA_OTEL_SCRAPE_INTERVAL}
          static_configs:
            - targets:
                - "${SCYLLA_EXPORTER_TARGET}"
EOF
)"

printf '%s\n' "${CONFIG}" | sudo tee "${OTELCOL_CONF_DIR}/scylladb.yaml" >/dev/null

echo "Wrote ${OTELCOL_CONF_DIR}/scylladb.yaml"
echo
echo "Merge steps (manual — pipeline lists are not auto-merged):"
echo "  1. Copy the receivers: block above into /etc/otelcol-contrib/config.yaml's"
echo "     top-level receivers: map."
echo "  2. Add 'prometheus/scylla' to the metrics pipeline's receivers list."
echo "  3. Restart otelcol-contrib (systemctl restart otelcol-contrib) to apply."
