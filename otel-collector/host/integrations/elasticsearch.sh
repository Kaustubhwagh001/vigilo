#!/usr/bin/env bash
# ------------------------------------------------------------
# vigilo — OTel Collector Contrib — Elasticsearch
# Purpose: render the native `elasticsearch` receiver (metrics) plus
#          `filelog`/`journald` receivers (logs) as a standalone config
#          snippet, for merging into the host-level otelcol-contrib config.
# Requires env: ELASTICSEARCH_EXPORTER_HOST, ELASTICSEARCH_EXPORTER_USER,
#               ELASTICSEARCH_EXPORTER_PASSWORD
# Optional env: ELASTICSEARCH_OTEL_ENDPOINT_SCHEME,
#               ELASTICSEARCH_OTEL_COLLECTION_INTERVAL,
#               ELASTICSEARCH_EXPORTER_SSL_SKIP_VERIFY,
#               ELASTICSEARCH_LOG_PATH, OTELCOL_CONF_DIR
# Usage: sudo ./elasticsearch.sh
#
# Note: this migrates `elasticsearch-otelcm .yml` from the source
# onboarding configs (filename had a literal trailing space before `.yml`
# in the source — not reproduced here). Unlike
# grafana-agent/integrations/elasticsearch.sh (which scrapes the
# `elasticsearch_exporter` sidecar's Prometheus endpoint), this uses OTel
# Collector Contrib's *native* `elasticsearch` receiver, which talks to the
# cluster's REST API directly — a genuinely different mechanism, not a
# duplicate. It reuses the same ELASTICSEARCH_EXPORTER_* env vars (host/
# user/password/ssl-skip-verify) since they describe the same cluster
# credentials either way.
#
# The source config's `elasticsearch.node.fs.disk.available` metric was
# explicitly disabled (`enabled: false`) — reproduced as-is below; flip it
# on by editing the generated file if you want that metric.
#
# This script does NOT install the otelcol-contrib binary or write the
# host's main config — that's owned by otel-collector/host/linux/'s
# installer. It only writes a receiver-only YAML snippet and prints the
# exact merge steps, since the collector does not deep-merge pipeline
# receiver lists across multiple --config files.
# ------------------------------------------------------------
set -euo pipefail

: "${ELASTICSEARCH_EXPORTER_HOST:?set ELASTICSEARCH_EXPORTER_HOST, e.g. 10.0.0.16:9200}"
: "${ELASTICSEARCH_EXPORTER_USER:?set ELASTICSEARCH_EXPORTER_USER, the metrics-reader account for this cluster}"
: "${ELASTICSEARCH_EXPORTER_PASSWORD:?set ELASTICSEARCH_EXPORTER_PASSWORD}"

ELASTICSEARCH_OTEL_ENDPOINT_SCHEME="${ELASTICSEARCH_OTEL_ENDPOINT_SCHEME:-https}"
ELASTICSEARCH_OTEL_COLLECTION_INTERVAL="${ELASTICSEARCH_OTEL_COLLECTION_INTERVAL:-1m}"
# The source cluster used a self-signed cert (insecure_skip_verify: true,
# hardcoded) — kept as the default here for parity with
# grafana-agent/integrations/elasticsearch.sh's ELASTICSEARCH_EXPORTER_SSL_SKIP_VERIFY
# default, but exposed as an env var so this can be turned off once the
# cluster has a CA-issued cert.
ELASTICSEARCH_EXPORTER_SSL_SKIP_VERIFY="${ELASTICSEARCH_EXPORTER_SSL_SKIP_VERIFY:-true}"
ELASTICSEARCH_LOG_PATH="${ELASTICSEARCH_LOG_PATH:-/var/log/elasticsearch/*.log}"
OTELCOL_CONF_DIR="${OTELCOL_CONF_DIR:-/etc/otelcol-contrib/conf.d}"

sudo mkdir -p "${OTELCOL_CONF_DIR}"

CONFIG="$(cat <<EOF
# Generated by otel-collector/host/integrations/elasticsearch.sh — merge
# into the host otelcol-contrib config; see the script header for exact
# steps.
receivers:
  elasticsearch:
    metrics:
      elasticsearch.node.fs.disk.available:
        enabled: false
    nodes: ["_local"]
    skip_cluster_metrics: false
    indices: ["_all"]
    endpoint: "${ELASTICSEARCH_OTEL_ENDPOINT_SCHEME}://${ELASTICSEARCH_EXPORTER_HOST}"
    username: "${ELASTICSEARCH_EXPORTER_USER}"
    password: "${ELASTICSEARCH_EXPORTER_PASSWORD}"
    tls:
      insecure: false
      insecure_skip_verify: ${ELASTICSEARCH_EXPORTER_SSL_SKIP_VERIFY}
    collection_interval: ${ELASTICSEARCH_OTEL_COLLECTION_INTERVAL}
  filelog/elasticsearch:
    start_at: beginning
    include_file_name: false
    include_file_path: true
    include:
      - ${ELASTICSEARCH_LOG_PATH}
      - /var/log/syslog
  journald/elasticsearch:
    directory: /var/log/journal
    units:
      - ssh.service
      - otelcol-contrib.service
    priority: info
    start_at: beginning
EOF
)"

printf '%s\n' "${CONFIG}" | sudo tee "${OTELCOL_CONF_DIR}/elasticsearch.yaml" >/dev/null

echo "Wrote ${OTELCOL_CONF_DIR}/elasticsearch.yaml"
echo
echo "Merge steps (manual — pipeline lists are not auto-merged):"
echo "  1. Copy the receivers: block above into /etc/otelcol-contrib/config.yaml's"
echo "     top-level receivers: map."
echo "  2. Add 'elasticsearch' to the metrics pipeline's receivers list."
echo "  3. Add 'filelog/elasticsearch' and 'journald/elasticsearch' to the logs"
echo "     pipeline's receivers list."
echo "  4. Restart otelcol-contrib (systemctl restart otelcol-contrib) to apply."
