#!/usr/bin/env bash
# ------------------------------------------------------------
# vigilo — OTel Collector (host, Contrib) — Cassandra
# Purpose: render the Cassandra metrics/logs receiver block for the
#          host-level otelcol-contrib collector (installed via the .deb
#          package by otel-collector/host/linux/*.sh) and print wiring
#          instructions — this script does NOT install the collector
#          binary itself.
# Requires env: CASSANDRA_EXPORTER_HOST, TENANT_ID
# Optional env: CASSANDRA_EXPORTER_CRITEO_PORT, DEPLOYMENT_ENVIRONMENT,
#               OTELCOL_CONF_DIR
# Usage: sudo ./cassandra.sh
#
# Note: OpenTelemetry Collector Contrib's `cassandrareceiver` scrapes
# Cassandra via JMX Metric Gatherer, but the source config this migrates
# from instead pointed a plain `prometheus` receiver at an
# already-running, separate Cassandra Prometheus exporter process (e.g.
# criteo/cassandra_exporter or instaclustr/cassandra-exporter) — that's
# what's reproduced here, for fidelity with what was actually run. If you
# want the JMX-based native receiver instead, swap the `prometheus/
# cassandra` block below for a `cassandrareceiver` block per
# https://github.com/open-telemetry/opentelemetry-collector-contrib/tree/main/receiver/cassandrareceiver
#
# Dedup note: the source had two Cassandra configs. One ran two real
# scrape jobs against a live exporter (ports 9500 and 8080 — the second
# labeled "criteo", likely a leftover from an exporter migration) but had
# no traces pipeline and leftover ScyllaDB journald units. The other had a
# fuller shape (otlp/jaeger trace receivers wired into an actual `traces`
# pipeline, richer resourcedetection attributes, a real
# `/var/log/cassandra/*.log` filelog path) but pointed its scrape job and
# otlp exporter at demo targets, and had process-name regexes left over
# from a shared mysql/redis template. This script merges the two: the
# fuller shape, wired back to the real (now templated) scrape target, with
# the Scylla/MySQL/Redis cross-contamination removed.
# ------------------------------------------------------------
set -euo pipefail

: "${CASSANDRA_EXPORTER_HOST:?set CASSANDRA_EXPORTER_HOST, e.g. 10.0.0.20:9500 — host:port of the already-running Cassandra Prometheus exporter}"
: "${TENANT_ID:?set TENANT_ID, e.g. my-tenant}"

CASSANDRA_EXPORTER_CRITEO_PORT="${CASSANDRA_EXPORTER_CRITEO_PORT:-}"
DEPLOYMENT_ENVIRONMENT="${DEPLOYMENT_ENVIRONMENT:-prod}"
OTELCOL_CONF_DIR="${OTELCOL_CONF_DIR:-/etc/otelcol-contrib/conf.d}"

sudo mkdir -p "${OTELCOL_CONF_DIR}"

EXTRA_TARGET_YAML=""
if [[ -n "${CASSANDRA_EXPORTER_CRITEO_PORT}" ]]; then
  CASSANDRA_EXPORTER_HOST_ONLY="${CASSANDRA_EXPORTER_HOST%%:*}"
  EXTRA_TARGET_YAML=$(cat <<EOF

        - job_name: 'cassandra-exporter-criteo'
          metrics_path: /metrics
          static_configs:
            - targets:
                - '${CASSANDRA_EXPORTER_HOST_ONLY}:${CASSANDRA_EXPORTER_CRITEO_PORT}'
EOF
)
fi

sudo tee "${OTELCOL_CONF_DIR}/cassandra.yaml" >/dev/null <<EOF
# Generated by otel-collector/host/integrations/cassandra.sh — do not hand
# edit; re-run the script to regenerate. This is NOT a standalone
# collector config: it's a fragment to merge into (or include from) the
# host-level otelcol-contrib config installed by
# otel-collector/host/linux/*.sh. See that config's own receivers:/
# processors:/service.pipelines: sections and splice the blocks below in —
# otelcol-contrib does not reliably merge pipeline receiver lists across
# multiple --config files, so this is meant to be copy/merged by hand (or
# by your own config-management templating) rather than included
# automatically.

receivers:
  prometheus/cassandra:
    config:
      scrape_configs:
        - job_name: 'cassandra-exporter'
          metrics_path: /metrics
          static_configs:
            - targets:
                - '${CASSANDRA_EXPORTER_HOST}'${EXTRA_TARGET_YAML}

  filelog/cassandra:
    start_at: beginning
    include_file_name: false
    include_file_path: true
    include:
      - /var/log/cassandra/*.log

  journald/cassandra:
    directory: /run/log/journal
    units:
      - ssh
      - cassandra
    priority: info

processors:
  resource/cassandra:
    attributes:
      - key: service.name
        value: "cassandra"
        action: upsert
      - key: tenant.id
        value: "${TENANT_ID}"
        action: upsert
      - key: deployment.environment
        value: "${DEPLOYMENT_ENVIRONMENT}"
        action: upsert

# Wiring instructions (manual merge into the host collector's config):
#   1. Add the three receivers above (prometheus/cassandra, filelog/
#      cassandra, journald/cassandra) to the top-level receivers: block.
#   2. Add resource/cassandra to the top-level processors: block.
#   3. In service.pipelines:
#        metrics: add prometheus/cassandra to receivers, resource/cassandra
#          to processors (alongside the existing resourcedetection/batch).
#        logs: add filelog/cassandra and journald/cassandra to receivers,
#          resource/cassandra to processors.
#      Traces are left to the host collector's own otlp/jaeger receivers
#      (if enabled) — this fragment adds no trace-specific processing.
#   4. Restart otelcol-contrib: sudo systemctl restart otelcol-contrib
EOF

echo "Wrote ${OTELCOL_CONF_DIR}/cassandra.yaml"
echo "This fragment is NOT auto-loaded — merge it into the host otelcol-contrib config per the instructions in the file, then: sudo systemctl restart otelcol-contrib"
