#!/usr/bin/env bash
# ------------------------------------------------------------
# vigilo — OTel Collector Contrib — Kafka
# Purpose: render a `prometheus` receiver with scrape jobs for per-broker
#          kafka_exporter, ZooKeeper exporter, and a Kafka consumer-lag
#          exporter, plus a `filelog` receiver, as a standalone config
#          snippet, for merging into the host-level otelcol-contrib config.
# Requires env: KAFKA_EXPORTER_TARGETS
# Optional env: ZOOKEEPER_EXPORTER_TARGETS, KAFKA_LAG_EXPORTER_TARGETS,
#               KAFKA_OTEL_LOG_PATH, OTELCOL_CONF_DIR
# Usage: sudo ./kafka-ssl.sh
#
# Note: this migrates `kafka_ssl_otel_config.yml` from the source
# onboarding configs. This is a genuinely separate integration mechanism
# from grafana-agent/integrations/kafka.sh (OTel's native `prometheus`
# receiver vs. Grafana Agent) — not a merge/reconciliation of the two.
#
# IMPORTANT — despite the source filename (and this script's name, kept
# for traceability back to that source), the source config contained NO
# Kafka broker TLS/SASL/keystore/truststore settings at all: it's a plain
# Prometheus-scrape-based config (kafka_exporter + ZooKeeper exporter +
# a kafka-lag exporter), identical in spirit to kafka.sh's external scrape
# job, just rendered as an OTel receiver instead of a Grafana Agent one. If
# you actually need Kafka client TLS/SASL (e.g. to point OTel Collector
# Contrib's `kafkametrics` receiver directly at brokers over SSL), that
# receiver's `auth`/`tls` block will need to be added separately — it is
# not reproduced here because the source never configured it. Flagged for
# human review in this folder's sanitization report.
#
# This script does NOT install the otelcol-contrib binary or write the
# host's main config — that's owned by otel-collector/host/linux/'s
# installer. It only writes a receiver-only YAML snippet and prints the
# exact merge steps, since the collector does not deep-merge pipeline
# receiver lists across multiple --config files.
# ------------------------------------------------------------
set -euo pipefail

: "${KAFKA_EXPORTER_TARGETS:?set KAFKA_EXPORTER_TARGETS, comma-separated host:port list of per-broker kafka_exporter instances, e.g. kafka-broker-1.example.com:7076,kafka-broker-2.example.com:7076}"

KAFKA_OTEL_LOG_PATH="${KAFKA_OTEL_LOG_PATH:-/kafka/log/*}"
OTELCOL_CONF_DIR="${OTELCOL_CONF_DIR:-/etc/otelcol-contrib/conf.d}"

# Renders a comma-separated list as an indented YAML sequence, one
# "- item" per line, so operators can pass target lists as plain env vars
# instead of hand-editing YAML. Mirrors
# grafana-agent/integrations/kafka.sh's csv_to_yaml_list helper.
csv_to_yaml_list() {
  local csv="$1" indent="$2" item
  local IFS=','
  for item in $csv; do
    printf '%s- "%s"\n' "$indent" "$item"
  done
}

KAFKA_TARGETS_YAML="$(csv_to_yaml_list "${KAFKA_EXPORTER_TARGETS}" "                ")"

# ZooKeeper exporter targets are optional — some Kafka deployments (e.g.
# KRaft mode) don't run ZooKeeper at all.
ZOOKEEPER_JOB_YAML=""
if [[ -n "${ZOOKEEPER_EXPORTER_TARGETS:-}" ]]; then
  ZOOKEEPER_TARGETS_YAML="$(csv_to_yaml_list "${ZOOKEEPER_EXPORTER_TARGETS}" "                ")"
  ZOOKEEPER_JOB_YAML="$(cat <<EOF
        - job_name: integrations/kafka-zookeeper
          static_configs:
            - targets:
${ZOOKEEPER_TARGETS_YAML}
EOF
)"
fi

# Consumer-lag exporter (e.g. danielqsj/kafka_exporter's lag metrics, or
# linkedin/Burrow) is also optional.
LAG_JOB_YAML=""
if [[ -n "${KAFKA_LAG_EXPORTER_TARGETS:-}" ]]; then
  LAG_TARGETS_YAML="$(csv_to_yaml_list "${KAFKA_LAG_EXPORTER_TARGETS}" "                ")"
  LAG_JOB_YAML="$(cat <<EOF
        - job_name: integrations/kafka_lag_export
          metrics_path: /metrics
          scrape_timeout: 60s
          static_configs:
            - targets:
${LAG_TARGETS_YAML}
EOF
)"
fi

sudo mkdir -p "${OTELCOL_CONF_DIR}"

CONFIG="$(cat <<EOF
# Generated by otel-collector/host/integrations/kafka-ssl.sh — merge into
# the host otelcol-contrib config; see the script header for exact steps.
# See the script header for why this is named "kafka-ssl" despite having
# no TLS/SASL config of its own.
receivers:
  prometheus/kafka:
    config:
      scrape_configs:
        - job_name: integrations/kafka
          scrape_timeout: 60s
          static_configs:
            - targets:
${KAFKA_TARGETS_YAML}
${ZOOKEEPER_JOB_YAML}
${LAG_JOB_YAML}
  filelog/kafka:
    start_at: beginning
    include_file_name: false
    include_file_path: true
    include:
      - ${KAFKA_OTEL_LOG_PATH}
      - /var/log/syslog
EOF
)"

printf '%s\n' "${CONFIG}" | sudo tee "${OTELCOL_CONF_DIR}/kafka-ssl.yaml" >/dev/null

echo "Wrote ${OTELCOL_CONF_DIR}/kafka-ssl.yaml"
echo
echo "Merge steps (manual — pipeline lists are not auto-merged):"
echo "  1. Copy the receivers: block above into /etc/otelcol-contrib/config.yaml's"
echo "     top-level receivers: map."
echo "  2. Add 'prometheus/kafka' to the metrics pipeline's receivers list."
echo "  3. Add 'filelog/kafka' to the logs pipeline's receivers list."
echo "  4. Restart otelcol-contrib (systemctl restart otelcol-contrib) to apply."
