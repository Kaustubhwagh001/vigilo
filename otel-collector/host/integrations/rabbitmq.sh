#!/usr/bin/env bash
# ------------------------------------------------------------
# vigilo — OTel Collector Contrib — RabbitMQ
# Purpose: enable RabbitMQ's built-in Prometheus plugin (if running locally
#          on this host) and render a `prometheus` receiver scrape job plus
#          a `journald` receiver as a standalone config snippet, for
#          merging into the host-level otelcol-contrib config.
# Requires env: RABBITMQ_EXPORTER_TARGET
# Optional env: RABBITMQ_OTEL_SCRAPE_INTERVAL, OTELCOL_CONF_DIR
# Usage: sudo ./rabbitmq.sh
#
# Note: this migrates `rabbitmq-otel.yaml` from the source onboarding
# configs. RabbitMQ exposes its own Prometheus-format metrics endpoint via
# the `rabbitmq_prometheus` plugin (no separate exporter binary needed) —
# per `rabbitmqreadme.txt`, the plugin is enabled with
# `rabbitmq-plugins enable rabbitmq_prometheus` and then verified with
# `curl localhost:15692/metrics`. This script runs that enable step
# automatically when `rabbitmq-plugins` is present on the local host (i.e.
# when the collector and broker are co-located); otherwise it's a no-op and
# you must run it on the broker yourself before the scrape job will return
# data. The source file's `hostmetrics` block is generic host-level
# collector config, not RabbitMQ-specific, and is already the job of
# otel-collector/host/linux/'s base config, so it's dropped here rather
# than duplicated.
#
# This script does NOT install the otelcol-contrib binary or write the
# host's main config — that's owned by otel-collector/host/linux/'s
# installer. It only writes a receiver-only YAML snippet and prints the
# exact merge steps, since the collector does not deep-merge pipeline
# receiver lists across multiple --config files.
# ------------------------------------------------------------
set -euo pipefail

: "${RABBITMQ_EXPORTER_TARGET:?set RABBITMQ_EXPORTER_TARGET, e.g. 10.0.0.18:15692 (host:port where rabbitmq_prometheus is exposed)}"

RABBITMQ_OTEL_SCRAPE_INTERVAL="${RABBITMQ_OTEL_SCRAPE_INTERVAL:-60s}"
OTELCOL_CONF_DIR="${OTELCOL_CONF_DIR:-/etc/otelcol-contrib/conf.d}"

if command -v rabbitmq-plugins >/dev/null 2>&1; then
  echo "Enabling rabbitmq_prometheus plugin on this host..."
  sudo rabbitmq-plugins enable rabbitmq_prometheus
else
  echo "rabbitmq-plugins not found on this host — if the broker runs elsewhere," >&2
  echo "run 'rabbitmq-plugins enable rabbitmq_prometheus' on it before this scrape" >&2
  echo "job will return data (verify with: curl \${RABBITMQ_EXPORTER_TARGET}/metrics)." >&2
fi

sudo mkdir -p "${OTELCOL_CONF_DIR}"

CONFIG="$(cat <<EOF
# Generated by otel-collector/host/integrations/rabbitmq.sh — merge into
# the host otelcol-contrib config; see the script header for exact steps.
receivers:
  prometheus/rabbitmq:
    config:
      global:
        scrape_interval: ${RABBITMQ_OTEL_SCRAPE_INTERVAL}
      scrape_configs:
        - job_name: 'rabbitmq-exporter'
          metrics_path: /metrics
          scrape_interval: ${RABBITMQ_OTEL_SCRAPE_INTERVAL}
          static_configs:
            - targets:
                - "${RABBITMQ_EXPORTER_TARGET}"
  journald/rabbitmq:
    directory: /run/log/journal
    units:
      - ssh
      - rabbitmq-server
    priority: info
EOF
)"

printf '%s\n' "${CONFIG}" | sudo tee "${OTELCOL_CONF_DIR}/rabbitmq.yaml" >/dev/null

echo "Wrote ${OTELCOL_CONF_DIR}/rabbitmq.yaml"
echo
echo "Merge steps (manual — pipeline lists are not auto-merged):"
echo "  1. Copy the receivers: block above into /etc/otelcol-contrib/config.yaml's"
echo "     top-level receivers: map."
echo "  2. Add 'prometheus/rabbitmq' to the metrics pipeline's receivers list."
echo "  3. Add 'journald/rabbitmq' to the logs pipeline's receivers list."
echo "  4. Restart otelcol-contrib (systemctl restart otelcol-contrib) to apply."
