#!/usr/bin/env bash
# ------------------------------------------------------------
# vigilo — OTel Collector (host, Contrib) — MongoDB
# Purpose: render the native `mongodb` receiver block (metrics, logs) for
#          the host-level otelcol-contrib collector (installed via the
#          .deb package by otel-collector/host/linux/*.sh) and print
#          wiring instructions — this script does NOT install the
#          collector binary itself.
# Requires env: MONGODB_HOST, MONGODB_USER, MONGODB_PASSWORD, TENANT_ID
# Optional env: MONGODB_REPLICA_SET, DEPLOYMENT_ENVIRONMENT,
#               OTELCOL_CONF_DIR
# Usage: sudo ./mongodb.sh
#
# Uses the OTel Collector Contrib `mongodbreceiver`
# (https://github.com/open-telemetry/opentelemetry-collector-contrib/blob/main/receiver/mongodbreceiver/documentation.md)
# — a direct wire-protocol connection to mongod/mongos, not a Prometheus
# scrape of a sidecar exporter. That's the genuinely different mechanism
# from grafana-agent/integrations/mongodb.sh (which drives the classic
# Grafana Agent's built-in mongodb_exporter integration instead).
#
# MongoDB replica sets have one `mongod` process per member, and this
# receiver connects to one `hosts[].endpoint` per collector instance — if
# you're monitoring more than one replica-set member, run this script once
# per member (each with its own MONGODB_HOST) on each member's host, or
# add additional `hosts:` entries by hand to the generated fragment.
#
# Dedup note: the source had three MongoDB configs. Two pointed at the
# same replica-set-member host (real IP redacted — not reproduced here or
# in the sanitization report) with an identical, full ~26-metric
# `metrics:` block (including an "enbaled: true" typo on
# mongodb.commands.rate, fixed here) — one of the two still carried unused
# otlp/jaeger trace receivers and a narrower resourcedetection detector
# list, and reads as an earlier draft of the other, cleaner config. Those
# two are treated as one canonical source and only the cleaner one's
# shape is kept. The third config pointed at a *different* replica-set
# member (a distinct, also-redacted host) and carried only 5 of the ~26
# metrics enabled —
# most likely a work-in-progress trim rather than an intentional reduced
# set (nothing in the source explains why a secondary would need less
# visibility than the primary), so it is NOT treated as a deliberate
# "lite" variant; this script ships the full metrics list and documents
# the replica-set-member host as something you set per invocation via
# MONGODB_HOST instead. journald support (ssh + mongodb units) from that
# third config is kept as a real, useful addition.
# ------------------------------------------------------------
set -euo pipefail

: "${MONGODB_HOST:?set MONGODB_HOST, e.g. 10.0.0.11:27017 — one replica-set member per invocation}"
: "${MONGODB_USER:?set MONGODB_USER, e.g. otel_metrics_reader}"
: "${MONGODB_PASSWORD:?set MONGODB_PASSWORD}"
: "${TENANT_ID:?set TENANT_ID, e.g. my-tenant}"

MONGODB_REPLICA_SET="${MONGODB_REPLICA_SET:-}"
DEPLOYMENT_ENVIRONMENT="${DEPLOYMENT_ENVIRONMENT:-prod}"
OTELCOL_CONF_DIR="${OTELCOL_CONF_DIR:-/etc/otelcol-contrib/conf.d}"

REPLICA_SET_LINE=""
if [[ -n "${MONGODB_REPLICA_SET}" ]]; then
  REPLICA_SET_LINE="    replica_set: ${MONGODB_REPLICA_SET}"
fi

sudo mkdir -p "${OTELCOL_CONF_DIR}"

sudo tee "${OTELCOL_CONF_DIR}/mongodb.yaml" >/dev/null <<EOF
# Generated by otel-collector/host/integrations/mongodb.sh — do not hand
# edit; re-run the script to regenerate. This is NOT a standalone
# collector config: it's a fragment to merge into (or include from) the
# host-level otelcol-contrib config installed by
# otel-collector/host/linux/*.sh. See that config's own receivers:/
# processors:/service.pipelines: sections and splice the blocks below in —
# otelcol-contrib does not reliably merge pipeline receiver lists across
# multiple --config files, so this is meant to be copy/merged by hand (or
# by your own config-management templating) rather than included
# automatically.

receivers:
  mongodb:
    hosts:
      - endpoint: ${MONGODB_HOST}
    username: ${MONGODB_USER}
    password: ${MONGODB_PASSWORD}
    collection_interval: 60s
    initial_delay: 10s
${REPLICA_SET_LINE}
    tls:
      insecure: true
      insecure_skip_verify: true
    metrics:
      mongodb.lock.acquire.count:
        enabled: true
      mongodb.lock.acquire.time:
        enabled: true
      mongodb.lock.acquire.wait_count:
        enabled: true
      mongodb.lock.deadlock.count:
        enabled: true
      mongodb.operation.latency.time:
        enabled: true
      mongodb.active.reads:
        enabled: true
      mongodb.active.writes:
        enabled: true
      mongodb.commands.rate:
        enabled: true
      mongodb.deletes.rate:
        enabled: true
      mongodb.flushes.rate:
        enabled: true
      mongodb.getmores.rate:
        enabled: true
      mongodb.health:
        enabled: true
      mongodb.inserts.rate:
        enabled: true
      mongodb.operation.repl.count:
        enabled: true
      mongodb.page_faults:
        enabled: true
      mongodb.queries.rate:
        enabled: true
      mongodb.repl_commands_per_sec:
        enabled: true
      mongodb.repl_deletes_per_sec:
        enabled: true
      mongodb.repl_getmores_per_sec:
        enabled: true
      mongodb.repl_inserts_per_sec:
        enabled: true
      mongodb.repl_queries_per_sec:
        enabled: true
      mongodb.repl_updates_per_sec:
        enabled: true
      mongodb.updates.rate:
        enabled: true
      mongodb.uptime:
        enabled: true
      mongodb.wtcache.bytes.read:
        enabled: true

  filelog/mongodb:
    include:
      - /var/log/mongo/*.log
    include_file_name: false
    include_file_path: true
    start_at: end

  journald/mongodb:
    directory: /run/log/journal
    units:
      - ssh
      - mongodb
    priority: info

processors:
  resource/mongodb:
    attributes:
      - key: service.name
        value: "mongodb"
        action: upsert
      - key: tenant.id
        value: "${TENANT_ID}"
        action: upsert
      - key: deployment.environment
        value: "${DEPLOYMENT_ENVIRONMENT}"
        action: upsert

# Wiring instructions (manual merge into the host collector's config):
#   1. Add the three receivers above (mongodb, filelog/mongodb, journald/
#      mongodb) to the top-level receivers: block.
#   2. Add resource/mongodb to the top-level processors: block.
#   3. In service.pipelines:
#        metrics: add mongodb to receivers, resource/mongodb to processors.
#        logs: add filelog/mongodb and journald/mongodb to receivers,
#          resource/mongodb to processors.
#   4. Restart otelcol-contrib: sudo systemctl restart otelcol-contrib
#
# ------------------------------------------------------------
# Creating the MongoDB read-only metrics user (run once, on the mongod
# primary, via mongosh/mongo shell as an admin):
#
#   use admin
#   db.createUser({
#     user: "\${MONGODB_USER}",
#     pwd: "\${MONGODB_PASSWORD}",
#     roles: [{ role: "read", db: "admin" }]
#   })
#
#   -- or, if the user already exists and just needs the monitoring role:
#   use admin
#   db.updateUser("\${MONGODB_USER}", {
#     roles: [
#       { role: "read", db: "admin" },
#       { role: "clusterMonitor", db: "admin" }
#     ]
#   })
#
# (Source note: the original runbook granted "read" on a specific
# application database rather than "admin" — grant "read" on whichever
# database(s) the receiver needs visibility into for your deployment, plus
# "clusterMonitor" on admin for replication/server-status metrics.)
# ------------------------------------------------------------
EOF

echo "Wrote ${OTELCOL_CONF_DIR}/mongodb.yaml"
echo "This fragment is NOT auto-loaded — merge it into the host otelcol-contrib config per the instructions in the file, then: sudo systemctl restart otelcol-contrib"
