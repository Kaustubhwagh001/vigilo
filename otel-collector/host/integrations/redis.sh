#!/usr/bin/env bash
# ------------------------------------------------------------
# vigilo — OTel Collector Contrib — Redis
# Purpose: render the native `redis` receiver (metrics) plus `filelog`/
#          `journald` receivers (logs) as a standalone config snippet,
#          for merging into the host-level otelcol-contrib config.
# Requires env: REDIS_HOST, REDIS_PASSWORD
# Optional env: REDIS_OTEL_COLLECTION_INTERVAL, REDIS_LOG_PATH,
#               REDIS_NORMALIZE_UPTIME_GAUGE, OTELCOL_CONF_DIR
# Usage: sudo ./redis.sh
#
# Note: this migrates `redisotelconfig.yml` and `redis_uptime_otelconfig.yml`
# from the source onboarding configs. Those two files are NOT two different
# integrations — they're the same Redis receiver config deployed to two
# different hosts/environments. Every difference between them was either
# deployment-specific (literal endpoint/password, a different
# `deployment.environment` resource value, a trimmed `resourcedetection`
# detector list, `start_at: end` vs `beginning` on filelog) or one genuine
# feature: `redis_uptime_otelconfig.yml` added a `transform/redis` processor
# that converts the `redis_uptime` counter to a gauge (handles the metric
# resetting to 0 on every Redis restart, which otherwise reads as a
# monotonic-counter reset to downstream tooling). That transform is folded
# in here as an opt-in processor via REDIS_NORMALIZE_UPTIME_GAUGE, rather
# than migrated as a second, near-duplicate script.
#
# This script does NOT install the otelcol-contrib binary or write the
# host's main config — that's owned by otel-collector/host/linux/'s
# installer. It only writes a receiver-only YAML snippet and prints the
# exact merge steps (which receiver/processor names to add to the metrics
# and logs pipelines in /etc/otelcol-contrib/config.yaml), since the
# collector does not deep-merge pipeline receiver/processor lists across
# multiple --config files.
# ------------------------------------------------------------
set -euo pipefail

: "${REDIS_HOST:?set REDIS_HOST, e.g. 10.0.0.15:6379}"
: "${REDIS_PASSWORD:?set REDIS_PASSWORD}"

REDIS_OTEL_COLLECTION_INTERVAL="${REDIS_OTEL_COLLECTION_INTERVAL:-60s}"
REDIS_LOG_PATH="${REDIS_LOG_PATH:-/var/log/redis/*.log}"
REDIS_NORMALIZE_UPTIME_GAUGE="${REDIS_NORMALIZE_UPTIME_GAUGE:-false}"
OTELCOL_CONF_DIR="${OTELCOL_CONF_DIR:-/etc/otelcol-contrib/conf.d}"

sudo mkdir -p "${OTELCOL_CONF_DIR}"

CONFIG="$(cat <<EOF
# Generated by otel-collector/host/integrations/redis.sh — merge into the
# host otelcol-contrib config; see the script header for exact steps.
receivers:
  redis:
    endpoint: "${REDIS_HOST}"
    collection_interval: ${REDIS_OTEL_COLLECTION_INTERVAL}
    password: "${REDIS_PASSWORD}"
  filelog/redis:
    include:
      - ${REDIS_LOG_PATH}
      - /var/log/syslog
    include_file_name: false
    include_file_path: true
    start_at: beginning
  journald/redis:
    directory: /run/log/journal
    units:
      - ssh
      - redis
      - redis-sentinel
    priority: info
EOF
)"

if [[ "${REDIS_NORMALIZE_UPTIME_GAUGE}" == "true" ]]; then
  CONFIG="${CONFIG}
processors:
  transform/redis:
    metric_statements:
      - context: metric
        statements:
          - convert_sum_to_gauge() where name == \"redis_uptime\"
"
fi

printf '%s\n' "${CONFIG}" | sudo tee "${OTELCOL_CONF_DIR}/redis.yaml" >/dev/null

echo "Wrote ${OTELCOL_CONF_DIR}/redis.yaml"
echo
echo "Merge steps (manual — pipeline lists are not auto-merged):"
echo "  1. Copy the receivers: (and, if enabled, processors:) blocks above"
echo "     into /etc/otelcol-contrib/config.yaml's top-level receivers:/processors: maps."
echo "  2. Add 'redis' to the metrics pipeline's receivers list."
echo "  3. Add 'filelog/redis' and 'journald/redis' to the logs pipeline's receivers list."
if [[ "${REDIS_NORMALIZE_UPTIME_GAUGE}" == "true" ]]; then
  echo "  4. Add 'transform/redis' to the metrics pipeline's processors list (after batch/resourcedetection)."
fi
echo "  5. Restart otelcol-contrib (systemctl restart otelcol-contrib) to apply."
